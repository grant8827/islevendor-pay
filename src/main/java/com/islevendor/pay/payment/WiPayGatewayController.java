package com.islevendor.pay.payment;

import com.islevendor.pay.config.PayProperties;
import java.net.URI;
import java.util.Map;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

/**
 * The addresses WiPay itself uses. Public (WiPay can't log in), so each one
 * proves itself: the return by WiPay's hash, the webhook by its signature.
 * Both URLs are generated by this service, never entered by an admin.
 */
@RestController
public class WiPayGatewayController {

    private final PaymentConfirmationService confirmations;
    private final PayProperties props;

    public WiPayGatewayController(PaymentConfirmationService confirmations, PayProperties props) {
        this.confirmations = confirmations;
        this.props = props;
    }

    /**
     * The customer coming back from WiPay's checkout. Always ends on the
     * marketplace's own payment page, which reads the verified result from
     * the server; the redirect target is built here, never taken from the query.
     */
    @GetMapping("/gateway/wipay/return")
    public ResponseEntity<Void> customerReturn(@RequestParam Map<String, String> query) {
        String target = confirmations.handleReturn(query)
                .map(intent -> props.marketplaceWebUrl() + "/payment/" + intent.getMarketplacePaymentId())
                .orElse(props.marketplaceWebUrl() + "/account");
        return ResponseEntity.status(HttpStatus.SEE_OTHER).location(URI.create(target)).build();
    }

    @PostMapping("/gateway/wipay/webhooks/payments")
    public Map<String, String> paymentsWebhook(
            @RequestBody byte[] body,
            @RequestHeader(name = "X-WiPay-Webhook-Signature", required = false) String signature,
            @RequestHeader(name = "X-WiPay-Webhook-Timestamp", required = false) String timestamp) {
        var outcome = confirmations.handleWebhook(body, signature, timestamp);
        return Map.of("outcome", outcome.name());
    }
}
